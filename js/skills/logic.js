/* ---------- Часы ---------- */
function clock(l) {
  let hh = rnd(1, 12), mm = [0, pick([0, 30]), pick([0, 15, 30, 45]), rnd(0, 11) * 5][l - 1];
  const f = (a, b) => `${a}:${String(b).padStart(2, '0')}`;
  const ans = f(hh, mm);
  const d = [f(hh % 12 + 1, mm), f(hh, (mm + 30) % 60), f((hh + 10) % 12 + 1, mm), f(mm / 5 || 12, hh * 5 % 60)];
  return { q: 'Который час показывают часы?', stage: clockSVG(hh, mm), choices: opts(ans, d.filter(x => x !== ans)).map(v => ({ v, label: v })), answer: ans, big: true, explain: `Короткая стрелка показывает часы, длинная — минуты. Сейчас ${ans}` };
}

