export function themeOf(child) {
  return THEMES[child.theme] || (child.gender === 'f' ? THEMES.princess : THEMES.knight);
}

export function applyTheme(child) {
  const t = child ? themeOf(child) : null;
  const r = document.documentElement.style;
  r.setProperty('--accent', t ? t.accent : '#3F7FD6');
  r.setProperty('--accent2', t ? t.accent2 : '#2A5BA3');
  r.setProperty('--soft', t ? t.soft : '#E4EEFB');
  r.setProperty('--page', t ? t.bg : 'linear-gradient(160deg,#EAF1FB 0%,#F6F2EA 100%)');
  const meta = document.querySelector('meta[name=theme-color]'); if (meta) meta.content = t ? t.soft : '#EAF1FB';
}

// Общая похвала с учётом рода: сделал/сделала
export function praiseFor(child) {
  const t = themeOf(child), f = child.gender === 'f';
  const common = ['Молодец!', 'Правильно!', 'Отлично!', 'Верно!', 'Здорово!', f ? 'Умница!' : 'Так держать!', 'Супер!', f ? 'Ты справилась!' : 'Ты справился!'];
  return [...common, ...t.praise];
}
